/** Public work summaries only; style never changes execution or approval policy. */
const TEACH_TEXT = `工作说明规则（替代之前的标题式播报要求）：
1. 像正在和用户协作一样，简短说明公开的行动、已确认的发现和接下来准备做什么。按下方配置选择措辞风格，通常一句话，必要时两句；不输出内部逐步推理或冗长分析。
2. 第一次实际开始工作时，先用一行说明准备做什么，再进行第一个工具调用；如果首条可见输出已经说明过，就不要重复。之后在多步骤任务完成实质阶段、发现影响判断的新证据、改变方法、遇到阻塞时再说明。不必每一步发言，不重复“正在处理/正在定位真正根因”，简单问题直接回答。
3. 示例：“我先核对温度模型的输入，再检查突变发生在哪一步。”“输入值已经对上，我正在检查插值和更新顺序。”“测试还没返回，我会等结果出来再判断。”只使用与实际工作相符的内容。
4. 为便于界面在折叠后保留这句话，每条工作说明独占一行，使用识别前缀“📌 进度：”，例如：
📌 进度：我先核对输入数据，再检查异常出现在哪一步。
此前的二级标题要求不再适用。前缀由插件隐藏，正文不要再加标签、标题、图标、加粗或套话。
5. 说明后继续已获授权的工作，不问“是否继续/需要我继续吗”，不因提醒结束本轮或等待确认。只有确实缺失关键条件、遇到实际审批或需要额外授权时才询问。
6. 不编造进展、百分比、剩余时间或成功结果。工具一直未返回时不能强行插话；操作前说明目的，返回后再说发现。不为播报额外轮询。
7. 已经有清楚的工作说明、没有新信息、或即将给最终结果时，无需凑一次播报。最终答复直接交付结果和必要限制。`

const NUDGE_TEXT = `已经有一段时间没有向用户说明工作状态。若还在执行任务，请在下一次继续操作前用一句工作说明交代“已确认到哪里、现在在做什么或接下来做什么”，行首使用“📌 进度：”。没有新结果也可以如实说明当前动作或阻塞，不编造进展、不重复旧结论。说明后继续已授权工作，不询问是否继续、不为说明额外轮询或结束本轮。若即将给最终结果，直接交付即可。`

const STYLES = {
  'first-person': '自然第一人称，例如“输入值已经核对，我正在检查更新顺序。”',
  stages: '简短的阶段进展报告，例如“输入核对已完成，接下来验证更新顺序。”不用阶段编号、标题或百分比。',
  cat: '轻微猫娘口吻，偶尔以“喵”收尾，例如“输入值已经核对，我接着检查更新顺序喵。”不角色扮演对话，不牺牲准确性。',
}
export function buildRules(config) {
  const style = config.narrationStyle === 'custom' ? (config.customStyle.trim() || STYLES['first-person']) : (STYLES[config.narrationStyle] || STYLES['first-person'])
  const guide = `本次工作说明风格：${style}\n风格仅影响工作说明的措辞；继续遵守上面的事实、简短、无装饰与继续工作的要求。`
  return { teach: TEACH_TEXT + '\n' + guide, nudge: NUDGE_TEXT + '\n' + guide }
}
